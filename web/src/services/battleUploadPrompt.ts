import type { Database } from '../types/domain';

/**
 * Build the copyable OCR prompt from the same catalog the client validates.
 * Including the full catalog prevents a model from silently inventing or
 * normalizing a near-match that the upload endpoint cannot accept. Portrait
 * ratios are derived from the 1080×2340 fixture and the production OCR crops in
 * image_extraction/extraction_config.json. Landscape ratios are measured from
 * the separate high-resolution 2532×1170 reference screenshot supplied for
 * this flow.
 */
export function buildDeepSeekBattlePrompt(database: Database): string {
  const heroSignatures = Object.fromEntries(
    Object.entries(database.heroes).map(([name, hero]) => [name, hero.skill])
  );
  const skillNames = Object.keys(database.skills);

  return `你是一名严格的《三国：谋定天下》战报 OCR 助手。请读取我随后上传的一张战报截图。只输出最终 JSON，不要输出分析过程、Markdown、注释或说明。

你可能直接看到图片，也可能只收到系统从图片中提取的、已经展平的 OCR 文本。即使 OCR 丢失了部分空间信息，也必须按照下面的行列规则重建阵容，不能把战法当成没有归属的全场汇总列表。

一、方向与阵容

1. 截图可能是原生竖屏、原生横屏、被手机旋转或留有黑边。先根据界面文字和 UI 标签把画面校正为文字正立的方向，再识别实际游戏画面的边界并排除纯黑边、系统栏或其他留白。下面的位置全部相对于这个“校正后的游戏画面区域”，只是粗略参考，允许约 5%～10% 偏差，不能当成固定像素裁剪，也不能按原始位图的旋转方向颠倒槽位顺序。
2. 阵容 1 始终是玩家/己方、与画面中的“胜 / 败”战果关联的一方；阵容 2 始终是对手/敌方。不要因为图片旋转或横竖布局改变而交换阵容。
3. 横屏通常是阵容 1 在左侧、阵容 2 在右侧。六张武将卡从左到右依次为阵容1[0]、阵容1[1]、阵容1[2]、阵容2[0]、阵容2[1]、阵容2[2]，“胜 / 败 / 平”位于画面顶部中央。
4. 竖屏通常是阵容 1 在上方、阵容 2 在下方。每个阵容的三张武将卡都从左到右排列，“胜 / 败 / 平”位于两个阵容之间。
5. 与阵容 1 关联的战果显示“胜”时 winner 为 "1"；显示“败”时 winner 为 "2"。
6. 若是平局，或画面明确显示开战前任一武将兵力已经减少/并非满编，或战报本身明确少于 6 个武将槽位，只输出 {"error":"无法处理：平局、开战前减员或武将槽位不完整"}。OCR 暂时认不出一个已经显示的武将不算缺少槽位，应按下文留空；战斗结束后显示的“溃灭”、0 兵力或伤亡是正常战果，不属于开战前减员。

二、最重要的战法归属规则

1. “战果”页面中的战法区域虽然显示发动次数、伤害和治疗统计，但它不是没有归属的全场战法汇总。
2. 每张武将卡正下方、处于相同横坐标范围内的一列固定属于该武将。每列从上到下的三行分别是 skills[0]（武将自带战法）、skills[1]（第一个携带战法）、skills[2]（第二个携带战法）。
3. 每行左侧的金色、紫色或其他彩色文字才是战法名。以下内容全部是战斗统计，必须忽略：“×1”“×4”“×20”等发动次数、红色交叉武器图标旁的伤害数字、绿色水滴图标旁的治疗数字，以及武将等级、剩余兵力、总兵力和战损数字。
4. 必须先按照武将卡和竖向分隔线划分列，再在每列中从上到下读取三个战法。不能按照伤害、发动次数或存活情况重排，也不能把 OCR 返回的扁平顺序直接当作最终归属；必须按第三节重新组合。
5. 必须独立检查双方 2×3 个武将位置和每格 3 个战法，共 6 名武将、18 个战法。

三、展平 OCR 文本的重组规则

1. 如果系统把横屏截图中的战法文字按照整页“从左到右、从上到下”展开，18 个战法通常会按行输出：前 6 个是六名武将的 skills[0]，中间 6 个是 skills[1]，最后 6 个是 skills[2]。
2. 必须按列重新组合：第 1 张武将卡使用第 1、7、13 个战法；第 2 张使用第 2、8、14 个；第 3 张使用第 3、9、15 个；第 4 张使用第 4、10、16 个；第 5 张使用第 5、11、17 个；第 6 张使用第 6、12、18 个。前三张属于阵容 1，后三张属于阵容 2。
3. 不能把最先出现的六个自带战法看成一组，再把后面的十二个携带战法随意分配。它们实际是一个三行六列的表格，必须转置后归入各武将列。
4. 对于竖屏截图，每个阵容分别是三列三行。若某个阵容的 9 个战法按行展开，第 1 张武将卡使用第 1、4、7 个战法，第 2 张使用第 2、5、8 个，第 3 张使用第 3、6、9 个。
5. 如果某个战法 OCR 不清晰，必须保留它所在的槽位，不能删除该项并导致后面的战法整体错位。若只能看到展平的 OCR 文本，先使用这些重组规则；不要仅因缺少坐标就放弃已经能够可靠归位的内容。

四、位置参考

1. 竖屏参考样本为 1080×2340：阵容 1 大约位于画面高度 15%～43%，阵容 2 大约位于 58%～82%，中间 44%～54% 是战果区域。三张武将卡中心横坐标约为 19%、50%、81%；阵容 1 的三行战法纵坐标约为 27%、31%、35%，阵容 2 约为 71%、75%、79%；胜负字粗略位于横坐标 10%～20%、纵坐标 45%～50%。
2. 横屏参考样本为 2532×1170：阵容 1 大约位于横坐标 11%～44%，阵容 2 大约位于 59%～92%，双方武将卡与战法主体都在画面高度约 22%～88%；“胜 / 败 / 平”位于顶部中央横坐标约 48%～54%、纵坐标约 8%～22%。六张武将卡中心横坐标约为 17%、28%、39%、64%、75%、86%，武将名大约位于画面高度 52%；各列战法名称的起始横坐标约为 12%、23%、34%、59%、70%、81%，每列三行战法大约位于画面高度 65%、74%、83%。
3. 位置只是辅助。必须优先根据武将卡边界、竖向分隔线和战法所在列判断归属；如果其他布局不同，不要强套坐标。

五、名称识别与目录校正

1. 不要先依赖难以辨认的武将名。对每张卡先读取 skills[0]，再使用下方“武将 → 自带战法”目录反查唯一对应的武将名；画面上的武将名只用于二次确认。
2. OCR 可能产生错字、漏字或形近字。例如，“茶藤心计”可能实际是目录中的“荼蘼心计”，“运筹惟”可能实际是“运筹帷幄”；只识别出“延前”等残缺文字时，需要结合原图位置和目录检查是否为“惩前毖后”。
3. 如果画面位置、可见字形和目录共同指向唯一候选，必须输出目录中完整、逐字一致的合法名称，不能输出 OCR 产生的错误名称。
4. 如果存在多个合理候选，不能根据常见配队或武将强度猜测。将该字段写成空字符串 ""，保留其他已经可靠识别的内容，供玩家手动修正。
5. 如果武将名已经确定，skills[0] 必须等于该武将在目录中的自带战法。skills[1] 和 skills[2] 可以是战法目录中的任意合法名称，包括其他武将的自带战法。
6. 同一阵容内已经确定的非空武将不能重名，已经确定的非空战法不能重名；两个对立阵容之间允许出现相同武将或相同战法。

六、输出格式

1. 即使只有个别名称无法确定，也要输出完整结构，并在对应位置使用空字符串 ""。不要因为一个槽位不清楚而放弃其他已经识别的内容。
2. 除前面规定的 error JSON 外，最外层只能有 "1"、"2"、"winner" 三个字段。每个阵容必须有按画面位置排列的 3 个对象；每个对象只能有 "name" 和 "skills"；skills 必须恰好有 3 项。
3. winner 只能是字符串 "1"、"2" 或无法确定时的空字符串 ""。
4. 只输出一份 JSON，不要输出思考过程、说明文字或 Markdown 代码围栏。

严格输出模板（把能够可靠确定的值填入对应位置，其余保持为空字符串）：
{"1":[{"name":"","skills":["","",""]},{"name":"","skills":["","",""]},{"name":"","skills":["","",""]}],"2":[{"name":"","skills":["","",""]},{"name":"","skills":["","",""]},{"name":"","skills":["","",""]}],"winner":""}

合法武将及其自带战法（JSON）：
${JSON.stringify(heroSignatures)}

合法战法名（JSON）：
${JSON.stringify(skillNames)}`;
}
